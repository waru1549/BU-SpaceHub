DO $$
DECLARE r record;
BEGIN
  FOR r IN SELECT * FROM (VALUES
    ('user_roles','role_id'),
    ('resource_categories','type_id'),
    ('resource_status','resource_status_id'),
    ('schedule_status','schedule_status_id'),
    ('booking_status','booking_status_id'),
    ('booking_actions','action_id'),
    ('users','user_id'),
